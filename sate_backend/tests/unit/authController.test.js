const prisma = require('../../src/lib/prisma');
const { criarResposta } = require('../helpers/resposta');
const controller = require('../../src/controllers/authController');

describe('authController', () => {
  beforeEach(() => jest.clearAllMocks());

  test('cadastro: dados obrigatórios', async () => {
    const res = criarResposta();
    await controller.cadastro({ body: {} }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('cadastro: senha curta', async () => {
    const res = criarResposta();
    await controller.cadastro({ body: { nome: 'Teste', email: 'teste@exemplo.com', senha: 'abc' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('login: tipo incorreto', async () => {
    const res = criarResposta();
    await controller.login({ body: { email: 'a@b.com', senha: '12345678', tipo: 'ADMIN' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });
});
