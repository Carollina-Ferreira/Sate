const prisma = require('../../src/lib/prisma');
const { criarResposta } = require('../helpers/resposta');
const controller = require('../../src/controllers/equipeController');

describe('equipeController', () => {
  beforeEach(() => jest.clearAllMocks());

  test('criar equipe: nome obrigatório', async () => {
    const res = criarResposta();
    prisma.treinador.findUnique.mockResolvedValue({ id: 1 });
    await controller.criarEquipe({ usuario: { id: 10 }, body: { modalidade: 'Futebol' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('criar equipe: modalidade obrigatória', async () => {
    const res = criarResposta();
    prisma.treinador.findUnique.mockResolvedValue({ id: 1 });
    await controller.criarEquipe({ usuario: { id: 10 }, body: { nome: 'Teste' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('listar equipes: treinador não identificado', async () => {
    const res = criarResposta();
    prisma.treinador.findUnique.mockResolvedValue(null);
    await controller.listarEquipes({ usuario: { id: 10 } }, res);
    expect(res.status).toHaveBeenCalledWith(401);
    expect(res.json).toHaveBeenCalled();
  });
});
