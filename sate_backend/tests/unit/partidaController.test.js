const prisma = require('../../src/lib/prisma');
const { criarResposta } = require('../helpers/resposta');
const controller = require('../../src/controllers/partidaController');

describe('partidaController', () => {
  beforeEach(() => jest.clearAllMocks());

  test('buscar partida: ID inválido', async () => {
    const res = criarResposta();
    await controller.buscarPartida({ params: { id: 'x' }, usuario: { id: 10 } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('criar partida: equipe obrigatória', async () => {
    const res = criarResposta();
    prisma.treinador.findUnique.mockResolvedValue({ id: 1 });
    await controller.criarPartida({ usuario: { id: 10 }, body: { adversario: 'Time B', data: '2026-11-30' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('criar partida: adversário obrigatório', async () => {
    const res = criarResposta();
    prisma.treinador.findUnique.mockResolvedValue({ id: 1 });
    await controller.criarPartida({ usuario: { id: 10 }, body: { equipeId: 1, data: '2026-11-30' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });
});
