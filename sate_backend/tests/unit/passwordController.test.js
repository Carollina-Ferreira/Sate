const prisma = require('../../src/lib/prisma');
const { criarResposta } = require('../helpers/resposta');
const controller = require('../../src/controllers/passwordController');

describe('passwordController', () => {
  beforeEach(() => jest.clearAllMocks());

  test('recuperação: e-mail obrigatório', async () => {
    const res = criarResposta();
    await controller.solicitarRecuperacao({ body: {} }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('redefinir senha: token obrigatório', async () => {
    const res = criarResposta();
    await controller.redefinirSenha({ body: { senha: 'minhasenha123' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('redefinir senha: mínimo de 8 caracteres', async () => {
    const res = criarResposta();
    await controller.redefinirSenha({ body: { token: 'token', senha: '123' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });
});
