const prisma = require('../../src/lib/prisma');
const { criarResposta } = require('../helpers/resposta');
const controller = require('../../src/controllers/usuarioController');

describe('usuarioController', () => {
  beforeEach(() => jest.clearAllMocks());

  test('buscar perfil: não encontrado', async () => {
    const res = criarResposta();
    prisma.usuario.findUnique.mockResolvedValue(null);
    await controller.buscarPerfil({ usuario: { id: 10 } }, res);
    expect(res.status).toHaveBeenCalledWith(404);
    expect(res.json).toHaveBeenCalled();
  });

  test('atualizar perfil: nome obrigatório', async () => {
    const res = criarResposta();
    await controller.atualizarPerfil({ usuario: { id: 10 }, body: { email: 'a@b.com' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });

  test('atualizar perfil: e-mail obrigatório', async () => {
    const res = criarResposta();
    await controller.atualizarPerfil({ usuario: { id: 10 }, body: { nome: 'Maria' } }, res);
    expect(res.status).toHaveBeenCalledWith(400);
    expect(res.json).toHaveBeenCalled();
  });
});
